/**
 * Train the Tanglish-vs-English word classifier and measure it.
 *
 *   npm run train
 *
 * 1. Word-level holdout: deterministic 80/20 split of the word lists.
 * 2. Sentence-level: hand-labelled code-mixed sentences; every word that appears
 *    in them is removed from training first, so these numbers are on unseen words.
 * 3. Retrain on everything and write src/langid/model.ts + data/metrics.json.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { LEXICON } from '../src/lexicon.js';
import { logOdds, trainNaiveBayes, type NaiveBayesModel } from '../src/langid/features.js';
import { tagWords } from '../src/langid/index.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const MAX_N = 4;
const ALPHA = 0.5;

function readWords(file: string): string[] {
  return readFileSync(join(root, 'data', file), 'utf8')
    .split(/\r?\n/)
    .map((l) => l.trim().toLowerCase())
    .filter((l) => l && !l.startsWith('#'));
}

const unique = (xs: string[]) => [...new Set(xs)];

let english = unique(readWords('english.txt'));
let tanglish = unique([...readWords('tanglish.txt'), ...Object.keys(LEXICON)]);
const conflicts = english.filter((w) => tanglish.includes(w));
if (conflicts.length) {
  console.warn(`Dropping ${conflicts.length} words listed as both languages: ${conflicts.join(', ')}`);
  english = english.filter((w) => !conflicts.includes(w));
  tanglish = tanglish.filter((w) => !conflicts.includes(w));
}

// FNV-1a hash → stable split independent of list order.
function hash(s: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return h >>> 0;
}
const isTest = (w: string) => hash(w) % 5 === 0;

// ---- 1. word holdout ------------------------------------------------------
const holdoutModel = trainNaiveBayes(english.filter((w) => !isTest(w)), tanglish.filter((w) => !isTest(w)), MAX_N, ALPHA);
const testEn = english.filter(isTest);
const testTa = tanglish.filter(isTest);
const correctEn = testEn.filter((w) => logOdds(holdoutModel, w) < 0).length;
const correctTa = testTa.filter((w) => logOdds(holdoutModel, w) >= 0).length;
const wordAcc = (correctEn + correctTa) / (testEn.length + testTa.length);
const misses = [
  ...testEn.filter((w) => logOdds(holdoutModel, w) >= 0).map((w) => `${w} (en→ta)`),
  ...testTa.filter((w) => logOdds(holdoutModel, w) < 0).map((w) => `${w} (ta→en)`),
];

// ---- 2. sentence eval on unseen words -------------------------------------
const sentences = readFileSync(join(root, 'data', 'eval-sentences.txt'), 'utf8')
  .split(/\r?\n/)
  .filter((l) => l.trim() && !l.startsWith('#'))
  .map((l) =>
    l.trim().split(/\s+/).map((tok) => {
      const [word, label] = tok.split('/');
      return { word, gold: label === 'T' ? 'tanglish' : 'en' };
    }),
  );
const sentenceWords = new Set(sentences.flat().map((t) => t.word.toLowerCase()));
const sentenceModel = trainNaiveBayes(
  english.filter((w) => !sentenceWords.has(w)),
  tanglish.filter((w) => !sentenceWords.has(w)),
  MAX_N,
  ALPHA,
);

function sentenceAccuracy(model: NaiveBayesModel, context: number): number {
  let correct = 0;
  let total = 0;
  for (const sent of sentences) {
    const tags = tagWords(sent.map((t) => t.word).join(' '), { model, context });
    sent.forEach((t, i) => {
      total++;
      if (tags[i].lang === t.gold) correct++;
    });
  }
  return correct / total;
}
const sentNoContext = sentenceAccuracy(sentenceModel, 0);
const sentContext = sentenceAccuracy(sentenceModel, 0.35);

const pct = (x: number) => `${(x * 100).toFixed(1)}%`;
console.log(`Training words: ${english.length} English, ${tanglish.length} Tanglish (char 1–${MAX_N}-grams)`);
console.log(`Word holdout accuracy (${testEn.length + testTa.length} unseen words): ${pct(wordAcc)}`);
console.log(`Sentence tokens (${sentences.flat().length}), no context:   ${pct(sentNoContext)}`);
console.log(`Sentence tokens (${sentences.flat().length}), with context: ${pct(sentContext)}`);
if (misses.length) console.log(`Holdout misses: ${misses.join(', ')}`);

// ---- 3. final model ---------------------------------------------------------
const model = trainNaiveBayes(english, tanglish, MAX_N, ALPHA);
const header = `// AUTO-GENERATED by scripts/train-langid.ts — do not edit by hand. Run \`npm run train\`.
// ${english.length} English + ${tanglish.length} Tanglish words, char 1–${MAX_N}-grams, ${model.vocab} features.
import type { NaiveBayesModel } from './features.js';

`;
writeFileSync(
  join(root, 'src', 'langid', 'model.ts'),
  `${header}export const MODEL: NaiveBayesModel = ${JSON.stringify(model)};\n`,
);
writeFileSync(
  join(root, 'data', 'metrics.json'),
  JSON.stringify(
    {
      englishWords: english.length,
      tanglishWords: tanglish.length,
      features: model.vocab,
      wordHoldout: { words: testEn.length + testTa.length, accuracy: +wordAcc.toFixed(4) },
      sentences: {
        tokens: sentences.flat().length,
        accuracyNoContext: +sentNoContext.toFixed(4),
        accuracyWithContext: +sentContext.toFixed(4),
      },
    },
    null,
    2,
  ) + '\n',
);
console.log(`Wrote src/langid/model.ts (${model.vocab} features)`);
